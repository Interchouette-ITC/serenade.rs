use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const COMPONENTS: [(&str, &str); 6] = [
    ("site_header", "site_header_view"),
    ("site_footer", "site_footer_view"),
    ("home", "home_view"),
    ("getting_started", "getting_started_view"),
    ("architecture", "architecture_view"),
    ("components", "components_view"),
];

fn main() {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let generated =
        PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is set")).join("rangular");
    std::fs::create_dir_all(&generated).expect("create rangular output directory");
    println!("cargo:rerun-if-changed=src/components");
    println!("cargo:rerun-if-changed=style/serenade.scss");

    let mut css = String::from("/* Generated by rangular from Serenade SCSS components. */\n");
    compile_stylesheet(
        &manifest.join("style/serenade.scss"),
        "serenade.scss",
        &mut css,
    );
    for (name, view_name) in COMPONENTS {
        compile_component(&manifest, &generated, &mut css, name, view_name);
    }

    let css_path = manifest.join("style/rangular.generated.css");
    std::fs::write(&css_path, css)
        .unwrap_or_else(|error| panic!("write generated component stylesheet: {error}"));
}

fn compile_stylesheet(path: &Path, label: &str, css: &mut String) {
    let scss = std::fs::read_to_string(path)
        .unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
    let compiled = rangular_css::compile_scss(&scss);
    assert!(compiled.ok(), "{label}: {:?}", compiled.issues);
    css.push_str(&compiled.css);
}

fn compile_component(
    manifest: &Path,
    generated: &Path,
    css: &mut String,
    name: &str,
    view_name: &str,
) {
    let component = manifest.join("src/components").join(name);
    let html_path = component.join(format!("{name}.html"));
    let html = std::fs::read_to_string(&html_path)
        .unwrap_or_else(|error| panic!("read {}: {error}", html_path.display()));
    let source = format!("src/components/{name}/{name}.html");
    let compiled = rangular_aot::compile_named(&html, &source, view_name);
    assert!(compiled.ok(), "{name}.html: {:?}", compiled.issues);
    std::fs::write(generated.join(format!("{view_name}.rs")), compiled.code)
        .unwrap_or_else(|error| panic!("write generated {name} view: {error}"));

    let scss_path = component.join(format!("{name}.scss"));
    let scss = std::fs::read_to_string(&scss_path)
        .unwrap_or_else(|error| panic!("read {}: {error}", scss_path.display()));
    let compiled = rangular_css::compile_scss(&scss);
    assert!(compiled.ok(), "{name}.scss: {:?}", compiled.issues);
    let _ = writeln!(css, "\n/* {name} */");
    css.push_str(&compiled.css);
}
